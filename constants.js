/** 输出格式指令（system 结尾），带本轮轮次。 */
export function buildOutputFormat(turn) {
  const t = Number(turn) > 0 ? Number(turn) : 1;
  return `【输出格式】严格按下面两段输出，不得增删其它任何内容：

第一段：叙事正文。直接开始写，不要任何包裹标签。
第二段：空一行后输出状态块，用 <state> 与 </state> 包裹，格式如下（第${t}轮）：

<state>
[第${t}轮]状态追踪：
时间：…
区域：…
在场角色+BUFF：…
不在场角色：…
处女膜状态：…
做爱次数：…
角色好感度：…
当前态度：…
身体外貌：…
重要记忆点：
- 角色名：记忆1|记忆2
</state>

状态块必须输出，即使本轮状态没有变化也要完整写出（无变化字段照抄 <previous_state>）。`;
}
